"""Compose the benchmark profile set from the ontology and the content bank.

Issue #172. `eval/profile_banks.py` holds the authored raw material; this module
turns it into the committed fixtures — `eval/profiles/<slug>.md` plus its
`<slug>.meta.json` sidecar — and nothing else may write them.

    python eval/profile_generator.py --write    # regenerate the profile set
    python eval/profile_generator.py --check    # fail if committed files drifted

**The markdown is generated, so hand-editing it is a defect, not a workflow.**
The issue's construction rule ("generate from the ontology, then hand-rewrite
every profile") is honoured by hand-authoring the *bank* and reading every
rendered file — not by editing rendered output, which would fork the fixture
away from the only source that explains it. `--check` and
`tests/test_profile_set.py` both assert the committed files are exactly what the
bank renders, so a drifted file fails the build instead of quietly becoming the
real dataset.

## Twenty profiles, not fifteen, and why that is the stronger design

The issue specifies 15 profiles — 5 role families x 3 variants — for n=3 per
family, after establishing that n=1 per stratum confounds *stratum* with
*profile identity*. That reasoning is kept, and the count changes for a reason
the issue's own design implies:

The three authored variants each differ from `specialist` on exactly one axis
(`generalist` on breadth, `metric_poor` on evidence density), which leaves
**redundancy with no contrast at all** — yet a redundancy-bearing fixture is one
of the issue's acceptance criteria, because #122 recorded that its four modes
could not fire on a fixture a human wrote to be non-redundant. A fourth authored
person per family would have supplied it, but the contrast would then confound
redundancy with that person's wording.

So the redundancy variant is **derived, not authored**: the `specialist` profile
with restating bullets appended to its first role and first project. The pair
differs in the hazard and in nothing else — same person, same employers, same
metrics, same skills — which is the cleanest form of the contrast available and
one the authored-only design cannot produce. The result is 15 authored people
plus 5 derivatives; family-level contrasts keep n=3 authored profiles exactly as
specified, and each hazard axis gets 5 matched pairs.

## What each profile declares

`role_family`, `level`, `breadth`, `evidence_density`, `redundancy` — the full
`REPORTED_STRATA` set, so no profile contributes a "missing" row to a slice.
Declaring is cheap and unverified, so `eval/profile_checks.py` verifies every
declaration against the rendered text: a fixture that *says* metric_poor and
carries numbers in every bullet would silently corrupt that slice, which is
worse than not slicing at all.
"""
from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from eval.profile_banks import (  # noqa: E402
    FAMILY_VOCAB,
    SLOTS,
    VARIANT_STRATA,
    Project,
    Role,
    Slot,
)
from eval.profile_ontology import REPORTED_STRATA, validate_strata  # noqa: E402

PROFILES_DIR = ROOT / "eval" / "profiles"

# Suffix for the derived redundancy-bearing variant. Sorted directory order then
# places it directly after the `specialist` profile it is derived from, which is
# also the profile it must be read against.
REDUNDANT_SUFFIX = "_redundant"

GENERATOR_NOTE = (
    "Generated by eval/profile_generator.py from eval/profile_banks.py "
    "(issue #172). Synthetic — no real résumé enters eval/. Edit the bank and "
    "rerun `python eval/profile_generator.py --write`; editing this file or the "
    "markdown directly is a defect that tests/test_profile_set.py fails on."
)


@dataclass(frozen=True)
class Composed:
    """One rendered profile: where it goes, what it says, what it declares."""
    slug: str
    strata: Dict[str, str]
    markdown: str
    sidecar: Dict
    slot: Slot
    redundant: bool

    @property
    def markdown_path(self) -> Path:
        return PROFILES_DIR / f"{self.slug}.md"

    @property
    def sidecar_path(self) -> Path:
        return PROFILES_DIR / f"{self.slug}.meta.json"


# ── composition ───────────────────────────────────────────────────────────────

def slug_for(slot: Slot, redundant: bool = False) -> str:
    """`data_science_specialist_priya_raman[_redundant]`.

    Family first so a sorted listing groups by the primary stratum, then the
    variant, then the person — a directory listing is the first thing anyone
    reads about this dataset and it should say what varies.
    """
    person = slot.name.lower().replace(" ", "_")
    return f"{slot.family}_{slot.variant}_{person}" + (
        REDUNDANT_SUFFIX if redundant else "")


def strata_for(slot: Slot, redundant: bool = False) -> Dict[str, str]:
    strata = {
        "role_family": slot.family,
        "level": slot.level,
        **VARIANT_STRATA[slot.variant],
        "redundancy": "bearing" if redundant else "clean",
    }
    # Declaration order is the ontology's, not the dict literal's, so two
    # profiles never write the same cell under different key orders.
    return {axis: strata[axis] for axis in REPORTED_STRATA}


def skills_for(slot: Slot) -> Tuple[str, ...]:
    """A specialist lists its family's vocabulary; a generalist adds the
    neighbouring families' as well.

    The breadth axis is a *vocabulary* difference rather than a wording one,
    which is what keeps it isolated: the two profiles' bullets are unrelated
    prose, but the axis under test moves exactly one thing — how many distinct
    technologies the candidate claims.
    """
    vocab = FAMILY_VOCAB[slot.family]
    if VARIANT_STRATA[slot.variant]["breadth"] == "generalist":
        return tuple(vocab["core"]) + tuple(vocab["adjacent"])
    return tuple(vocab["core"])


def _with_redundancy(slot: Slot) -> Tuple[List[Role], List[Project]]:
    """Restating bullets appended to the first role and the first project.

    Appended rather than substituted, so the base profile's content is a strict
    prefix of this one: every bullet the clean variant carries is still here,
    word for word, and any metric that moves between the pair moved because of
    the padding.

    First role and first project specifically, because
    `agents/redundancy.py::new_information_ratio` measures *within* an item —
    two projects legitimately restate a shared technology, while a bullet
    repeating the bullet above it in the same role is padding.
    """
    roles = list(slot.roles)
    projects = list(slot.projects)
    if slot.redundant_role_bullets:
        first = roles[0]
        roles[0] = Role(first.company, first.title, first.dates,
                        first.bullets + slot.redundant_role_bullets)
    if slot.redundant_project_bullets:
        first = projects[0]
        projects[0] = Project(first.name, first.descriptor,
                              first.bullets + slot.redundant_project_bullets,
                              url=first.url, github=first.github)
    return roles, projects


def compose(slot: Slot, redundant: bool = False) -> Composed:
    roles, projects = _with_redundancy(slot) if redundant else (
        list(slot.roles), list(slot.projects))
    strata = strata_for(slot, redundant)
    validate_strata(strata, source=slug_for(slot, redundant))
    skills = skills_for(slot)
    return Composed(
        slug=slug_for(slot, redundant),
        strata=strata,
        markdown=render_markdown(slot, roles, projects, skills),
        sidecar=render_sidecar(slot, projects, strata, redundant),
        slot=slot,
        redundant=redundant,
    )


def all_profiles() -> List[Composed]:
    """Every profile in the set: each authored slot, plus the derived
    redundancy-bearing variant of every slot that supplies restating bullets."""
    out: List[Composed] = []
    for slot in SLOTS:
        out.append(compose(slot))
        if slot.redundant_role_bullets or slot.redundant_project_bullets:
            out.append(compose(slot, redundant=True))
    return out


# ── rendering ─────────────────────────────────────────────────────────────────

_SKILL_LINE_WIDTH = 78


def _email(name: str) -> str:
    return name.lower().replace(" ", ".") + "@example.com"


def _linkedin(name: str) -> str:
    return "linkedin.com/in/" + name.lower().replace(" ", "-")


def _wrap_skills(skills: Tuple[str, ...]) -> List[str]:
    """Comma-separated, wrapped on width — the shape `_parse_skills` reads and
    the shape a résumé actually uses. Deterministic: wrapping is a function of
    the names alone."""
    lines: List[str] = []
    current = ""
    for i, skill in enumerate(skills):
        piece = skill + ("," if i < len(skills) - 1 else "")
        if current and len(current) + 1 + len(piece) > _SKILL_LINE_WIDTH:
            lines.append(current)
            current = piece
        else:
            current = f"{current} {piece}".strip()
    if current:
        lines.append(current)
    return lines


def render_markdown(slot: Slot, roles: List[Role], projects: List[Project],
                    skills: Tuple[str, ...]) -> str:
    """The fixture shape `eval/profile_fixture.py` parses and the real ingest
    pipeline reads — one renderer, so no profile can drift into a private
    dialect of it."""
    out: List[str] = [f"# {slot.name}", ""]
    out.append(f"{_email(slot.name)} | {_linkedin(slot.name)} | github.com/{slot.handle}")
    out += ["", "## Summary", slot.summary, "", "## Experience", ""]

    for role in roles:
        out.append(f"**{role.company}** — {role.title} ({role.dates})")
        out += [f"- {b}" for b in role.bullets]
        out.append("")

    out += ["## Projects", ""]
    for project in projects:
        header = f"**{project.name}**"
        if project.url:
            header += f" ({project.url})"
        header += f" — {project.descriptor}"
        out.append(header)
        out += [f"- {b}" for b in project.bullets]
        out.append("")

    out += ["## Skills"] + _wrap_skills(skills) + ["", "## Education", slot.education]
    if slot.achievements:
        out += ["", "## Achievements"] + list(slot.achievements)
    return "\n".join(out).rstrip() + "\n"


def render_sidecar(slot: Slot, projects: List[Project], strata: Dict[str, str],
                   redundant: bool) -> Dict:
    """The sidecar `eval/profile_meta.py` loads.

    `distractors` is written empty rather than omitted: the distractor pool is a
    later chunk of #172, and an empty-but-present section is the difference
    between "no distractors injected" and "this fixture predates the idea".
    """
    metrics = {p.name: dict(p.github) for p in projects if p.github}
    notes = GENERATOR_NOTE
    if redundant:
        notes += (
            f" Redundancy-bearing derivative of "
            f"`{slug_for(slot)}.md`: identical except for restating bullets "
            "appended to the first role and first project, so the pair isolates "
            "the redundancy axis on one synthetic person (#122).")
    return {
        "strata": strata,
        "notes": notes,
        "github_metrics": {name: metrics[name] for name in sorted(metrics)},
        "distractors": {"skills": [], "projects": []},
    }


def _sidecar_text(sidecar: Dict) -> str:
    return json.dumps(sidecar, indent=2, ensure_ascii=False) + "\n"


# ── write / check ─────────────────────────────────────────────────────────────

def write_all(profiles_dir: Path = PROFILES_DIR) -> List[Path]:
    profiles_dir.mkdir(parents=True, exist_ok=True)
    written: List[Path] = []
    for profile in all_profiles():
        md = profiles_dir / f"{profile.slug}.md"
        meta = profiles_dir / f"{profile.slug}.meta.json"
        md.write_text(profile.markdown, encoding="utf-8")
        meta.write_text(_sidecar_text(profile.sidecar), encoding="utf-8")
        written += [md, meta]
    return written


def drifted(profiles_dir: Path = PROFILES_DIR) -> List[str]:
    """Committed files that are missing or no longer match the bank."""
    problems: List[str] = []
    for profile in all_profiles():
        for path, expected in (
            (profiles_dir / f"{profile.slug}.md", profile.markdown),
            (profiles_dir / f"{profile.slug}.meta.json", _sidecar_text(profile.sidecar)),
        ):
            if not path.exists():
                problems.append(f"missing: {path.name}")
            elif path.read_text(encoding="utf-8") != expected:
                problems.append(f"drifted: {path.name}")
    return problems


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="regenerate the profile set")
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if any committed file drifted from the bank")
    ap.add_argument("--dir", type=Path, default=PROFILES_DIR)
    args = ap.parse_args(argv)

    if args.write:
        written = write_all(args.dir)
        print(f"wrote {len(written)} files for {len(all_profiles())} profiles "
              f"→ {args.dir}")
        return 0

    problems = drifted(args.dir)
    if problems:
        print("profile set is out of date with eval/profile_banks.py:")
        for problem in problems:
            print(f"  {problem}")
        print("\nrun: python eval/profile_generator.py --write")
        return 1
    if args.check:
        print(f"{len(all_profiles())} profiles match the bank")
    else:
        for profile in all_profiles():
            print(f"{profile.slug}  {profile.strata}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
